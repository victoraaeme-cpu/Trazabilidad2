begin
  if not exists (
    select 1 from pg_proc p join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public' and p.proname = 'is_staff'
  ) then
    execute $f$
      create function public.is_staff()
      returns boolean
      language sql
      stable
      security definer
      set search_path = pg_catalog, public, auth
      as $body$
        select exists (
          select 1 from public.staff_usuarios s
          where lower(s.email) = lower(coalesce(auth.jwt()->>'email', ''))
        );
      $body$
    $f$;
    execute 'revoke all on function public.is_staff() from public, anon';
    execute 'grant execute on function public.is_staff() to authenticated';
  end if;
end;
$$;

