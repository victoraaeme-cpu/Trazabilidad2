create or replace function public.asignar_inventario_ubicacion(
  p_ubicacion_codigo text,
  p_folio text,
  p_items jsonb
)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_ubicacion public.ubicaciones%rowtype;
  v_almacen public.almacenes%rowtype;
  v_almacen_codigo text;
  v_item jsonb;
  v_material public.materiales%rowtype;
  v_anterior_codigo text;
  v_anterior text;
  v_anterior_almacen_codigo text;
  v_codigo text;
  v_procesados integer := 0;
begin
  if not (public.is_staff() or public.is_admin()) then
    raise exception 'NO_AUTORIZADO';
  end if;
  if coalesce(trim(p_folio), '') = ''
    or jsonb_typeof(p_items) <> 'array'
    or jsonb_array_length(p_items) = 0 then
    raise exception 'DATOS_DE_ASIGNACION_INVALIDOS';
  end if;

  select almacen_codigo into v_almacen_codigo
  from public.ubicaciones
  where codigo = p_ubicacion_codigo;
  if not found then
    raise exception 'UBICACION_NO_ENCONTRADA';
  end if;

  select * into v_almacen
  from public.almacenes
  where codigo = v_almacen_codigo
  for key share;
  if not found then
    raise exception 'ALMACEN_NO_ENCONTRADO';
  end if;

  select * into v_ubicacion
  from public.ubicaciones
  where codigo = p_ubicacion_codigo
  for update;
  if not found or v_ubicacion.almacen_codigo <> v_almacen.codigo then
    raise exception 'UBICACION_CAMBIO_DURANTE_ASIGNACION';
  end if;

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    v_codigo := nullif(trim(v_item->>'codigo'), '');
    if v_codigo is null then
      raise exception 'CODIGO_MATERIAL_INVALIDO';
    end if;

    select * into v_material
    from public.materiales
    where codigo = v_codigo
    for update;
    if not found then
      raise exception 'MATERIAL_NO_ENCONTRADO: %', v_codigo;
    end if;

    v_anterior_codigo := nullif(v_material.data->>'ubicacionCodigo', '');
    v_anterior := nullif(v_material.data->>'ubicacion', '');
    v_anterior_almacen_codigo := nullif(v_material.data->>'ubicacionAlmacenCodigo', '');

    update public.materiales
    set data = jsonb_set(
      jsonb_set(
        jsonb_set(
          jsonb_set(coalesce(v_material.data, '{}'::jsonb), '{ubicacion}', to_jsonb(v_ubicacion.nombre), true),
          '{ubicacionCodigo}', to_jsonb(v_ubicacion.codigo), true
        ),
        '{ubicacionAlmacenCodigo}', to_jsonb(v_almacen.codigo), true
      ),
      '{ubicacionAlmacenNombre}', to_jsonb(v_almacen.nombre), true
    )
    where codigo = v_codigo;

    insert into public.movimientos_ubicacion (
      folio, codigo_material, ubicacion_anterior_codigo, ubicacion_anterior,
      ubicacion_nueva_codigo, ubicacion_nueva,
      ubicacion_anterior_almacen_codigo, ubicacion_nueva_almacen_codigo,
      existencia
    )
    values (
      p_folio, v_codigo, v_anterior_codigo, v_anterior,
      v_ubicacion.codigo, v_ubicacion.nombre,
      v_anterior_almacen_codigo, v_almacen.codigo,
      coalesce(v_item->'existencia', '{}'::jsonb)
    );

    v_procesados := v_procesados + 1;
  end loop;

  return v_procesados;
end;
$$;

revoke all on function public.asignar_inventario_ubicacion(text, text, jsonb) from public, anon;
grant execute on function public.asignar_inventario_ubicacion(text, text, jsonb) to authenticated;

create or replace function public.eliminar_ubicacion_vacia(
  p_ubicacion_codigo text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_ubicacion public.ubicaciones%rowtype;
  v_materiales integer;
  v_movimientos integer;
begin
  if not public.is_admin() then
    raise exception 'NO_AUTORIZADO';
  end if;

  select * into v_ubicacion
  from public.ubicaciones
  where codigo = p_ubicacion_codigo
  for update;
  if not found then
    raise exception 'UBICACION_NO_ENCONTRADA';
  end if;

  select count(*)::integer into v_materiales
  from public.materiales
  where data->>'ubicacionCodigo' = v_ubicacion.codigo
    or (
      data->>'ubicacionCodigo' is null
      and lower(trim(data->>'ubicacion')) = lower(v_ubicacion.nombre)
      and (
        data->>'ubicacionAlmacenCodigo' is null
        or data->>'ubicacionAlmacenCodigo' = v_ubicacion.almacen_codigo
      )
    );

  select count(*)::integer into v_movimientos
  from public.movimientos_ubicacion
  where ubicacion_anterior_codigo = v_ubicacion.codigo
    or ubicacion_nueva_codigo = v_ubicacion.codigo
    or (
      ubicacion_anterior_codigo is null
      and lower(trim(ubicacion_anterior)) = lower(v_ubicacion.nombre)
    )
    or (
      ubicacion_nueva_codigo is null
      and lower(trim(ubicacion_nueva)) = lower(v_ubicacion.nombre)
    );

  if v_materiales > 0 then
    raise exception 'UBICACION_NO_VACIA: materiales=%, movimientos=%', v_materiales, v_movimientos;
  end if;

  delete from public.ubicaciones where codigo = v_ubicacion.codigo;
  return jsonb_build_object(
    'ubicacion_eliminada', v_ubicacion.codigo,
    'movimientos_conservados', v_movimientos
  );
end;
$$;

create or replace function public.eliminar_almacen_inventario(
  p_almacen_codigo text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_almacen public.almacenes%rowtype;
  v_ubicaciones text[];
  v_materiales integer := 0;
  v_movimientos integer := 0;
begin
  if not public.is_admin() then
    raise exception 'NO_AUTORIZADO';
  end if;

  select * into v_almacen
  from public.almacenes
  where codigo = p_almacen_codigo
  for update;
  if not found then
    raise exception 'ALMACEN_NO_ENCONTRADO';
  end if;

  perform 1
  from public.ubicaciones
  where almacen_codigo = v_almacen.codigo
  order by codigo
  for update;

  select coalesce(array_agg(codigo), '{}'::text[])
  into v_ubicaciones
  from public.ubicaciones
  where almacen_codigo = v_almacen.codigo;

  update public.materiales
  set data = coalesce(data, '{}'::jsonb)
    - 'ubicacion'
    - 'ubicacionCodigo'
    - 'ubicacionAlmacenCodigo'
    - 'ubicacionAlmacenNombre'
  where data->>'ubicacionAlmacenCodigo' = v_almacen.codigo
    or data->>'ubicacionCodigo' = any(v_ubicaciones)
    or (
      data->>'ubicacionCodigo' is null
      and exists (
        select 1 from public.ubicaciones ubicacion
        where ubicacion.codigo = any(v_ubicaciones)
          and lower(trim(data->>'ubicacion')) = lower(ubicacion.nombre)
      )
    );
  get diagnostics v_materiales = row_count;

  delete from public.movimientos_ubicacion
  where ubicacion_anterior_almacen_codigo = v_almacen.codigo
    or ubicacion_nueva_almacen_codigo = v_almacen.codigo
    or ubicacion_anterior_codigo = any(v_ubicaciones)
    or ubicacion_nueva_codigo = any(v_ubicaciones)
    or (
      ubicacion_anterior_codigo is null
      and exists (
        select 1 from public.ubicaciones ubicacion
        where ubicacion.codigo = any(v_ubicaciones)
          and lower(trim(public.movimientos_ubicacion.ubicacion_anterior)) = lower(ubicacion.nombre)
      )
    )
    or (
      ubicacion_nueva_codigo is null
      and exists (
        select 1 from public.ubicaciones ubicacion
        where ubicacion.codigo = any(v_ubicaciones)
          and lower(trim(public.movimientos_ubicacion.ubicacion_nueva)) = lower(ubicacion.nombre)
      )
    );
  get diagnostics v_movimientos = row_count;

  delete from public.ubicaciones where almacen_codigo = v_almacen.codigo;
  delete from public.almacenes where codigo = v_almacen.codigo;

  return jsonb_build_object(
    'almacen_eliminado', v_almacen.codigo,
    'ubicaciones_eliminadas', cardinality(v_ubicaciones),
    'materiales_desvinculados', v_materiales,
    'movimientos_eliminados', v_movimientos
  );
end;
$$;

