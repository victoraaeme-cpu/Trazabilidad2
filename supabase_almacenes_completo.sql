create or replace function public.registrar_conteo_ciclico(
  p_codigo_material text,
  p_ubicacion_codigo text,
  p_existencia_anterior numeric,
  p_existencia_contada numeric,
  p_unidad text,
  p_motivo text default ''
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_ubicacion public.ubicaciones%rowtype;
  v_material public.materiales%rowtype;
  v_id bigint;
  v_es_mp boolean;
  v_modo_longitud boolean;
  v_longitud numeric;
  v_unidad text;
  v_factor numeric;
  v_total numeric;
  v_surtido numeric;
  v_ajustes numeric;
  v_existencia numeric;
begin
  if not public.is_admin() then
    raise exception 'NO_AUTORIZADO';
  end if;
  if coalesce(trim(p_codigo_material), '') = ''
    or coalesce(trim(p_ubicacion_codigo), '') = ''
    or p_existencia_anterior is null
    or p_existencia_contada is null
    or p_existencia_anterior::text in ('NaN', 'Infinity', '-Infinity')
    or p_existencia_contada::text in ('NaN', 'Infinity', '-Infinity')
    or p_existencia_contada < 0
    or p_unidad is null
    or p_unidad not in ('PZ', 'mm', 'cm', 'm', 'in')
    or length(coalesce(p_motivo, '')) > 300 then
    raise exception 'DATOS_DE_CONTEO_INVALIDOS';
  end if;

  select * into v_ubicacion
  from public.ubicaciones
  where codigo = p_ubicacion_codigo
  for update;
  if not found then
    raise exception 'UBICACION_NO_ENCONTRADA';
  end if;

  select * into v_material
  from public.materiales
  where codigo = p_codigo_material
  for update;
  if not found then
    raise exception 'MATERIAL_NO_ENCONTRADO';
  end if;
  if v_material.data->>'ubicacionCodigo' is distinct from v_ubicacion.codigo
    and not (
      nullif(v_material.data->>'ubicacionCodigo', '') is null
      and lower(trim(coalesce(v_material.data->>'ubicacion', ''))) = lower(trim(v_ubicacion.nombre))
      and (
        v_material.data->>'ubicacionAlmacenCodigo' is null
        or v_material.data->>'ubicacionAlmacenCodigo' = v_ubicacion.almacen_codigo
      )
    ) then
    raise exception 'MATERIAL_CAMBIO_DE_UBICACION';
  end if;

  v_es_mp := lower(coalesce(v_material.data->>'tipoRegistro', '')) in ('mp', 'materia prima')
    or lower(coalesce(v_material.data->>'esMP', 'false')) = 'true';
  v_longitud := coalesce(nullif(v_material.data->>'longitudIndividual', '')::numeric, 0);
  if v_longitud > 0 then
    v_unidad := 'mm';
  else
    v_longitud := coalesce(nullif(v_material.data->>'longitud', '')::numeric, 0);
    v_unidad := coalesce(
      nullif(v_material.data->>'longU', ''),
      nullif(v_material.data->>'longitudUnidad', ''),
      'mm'
    );
    if v_unidad not in ('mm', 'cm', 'm', 'in') then
      v_unidad := 'mm';
    end if;
  end if;
  v_modo_longitud := v_es_mp and v_longitud > 0;

  select coalesce(sum(diferencia), 0)
  into v_ajustes
  from public.ajustes_inventario_ciclico
  where codigo_material = p_codigo_material;

  if v_modo_longitud then
    if p_unidad <> v_unidad then
      raise exception 'UNIDAD_DE_CONTEO_INVALIDA';
    end if;
    v_factor := case v_unidad when 'mm' then 1 when 'cm' then 10 when 'm' then 1000 else 25.4 end;
    v_total := coalesce(nullif(v_material.data->>'cantidad', '')::numeric, 0) * v_longitud;

    select coalesce(sum(
      coalesce(nullif(d.data->>'longitud', '')::numeric, 0)
      * (case d.data->>'unidad'
          when 'mm' then 1
          when 'cm' then 10
          when 'm' then 1000
          when 'in' then 25.4
          else v_factor
        end) / v_factor
    ), 0)
    into v_surtido
    from public.despachos d
    where d.codigo = p_codigo_material;

    v_existencia := floor((v_total - v_surtido + v_ajustes) * 10000 + 0.5) / 10000;
  else
    if p_unidad <> 'PZ' then
      raise exception 'UNIDAD_DE_CONTEO_INVALIDA';
    end if;
    v_total := coalesce(nullif(v_material.data->>'cantidad', '')::numeric, 0);

    select coalesce(sum(coalesce(nullif(d.data->>'cantidad', '')::numeric, 0)), 0)
    into v_surtido
    from public.despachos d
    where d.codigo = p_codigo_material;

    v_existencia := floor((v_total - v_surtido + v_ajustes) * 10000 + 0.5) / 10000;
  end if;

  if abs(v_existencia - p_existencia_anterior) > 0.00005 then
    raise exception 'EXISTENCIA_CAMBIO_DURANTE_CONTEO';
  end if;

  insert into public.ajustes_inventario_ciclico (
    codigo_material, ubicacion_codigo, ubicacion_nombre,
    existencia_anterior, existencia_contada, diferencia, unidad, motivo, usuario
  )
  values (
    p_codigo_material, v_ubicacion.codigo, v_ubicacion.nombre,
    v_existencia, p_existencia_contada,
    p_existencia_contada - v_existencia,
    p_unidad, trim(coalesce(p_motivo, '')),
    coalesce(nullif(auth.jwt()->>'email', ''), 'Administrador')
  )
  returning id into v_id;

  return jsonb_build_object('id', v_id, 'diferencia', p_existencia_contada - v_existencia);
end;
$$;

